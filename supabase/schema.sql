create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  match_code text not null unique,
  home_team text not null,
  away_team text not null,
  match_date timestamptz not null,
  venue text not null,
  available_seats integer not null check (available_seats >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete restrict,
  customer_name text not null check (char_length(customer_name) between 2 and 60),
  customer_email text not null,
  customer_phone text not null check (customer_phone ~ '^[0-9]{10}$'),
  stand_category text not null check (stand_category in ('general', 'premium', 'hospitality')),
  ticket_count integer not null check (ticket_count between 1 and 10),
  aisle_seats boolean not null default false,
  accessible_seating boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.matches enable row level security;
alter table public.bookings enable row level security;

drop policy if exists "Matches are readable by everyone" on public.matches;
create policy "Matches are readable by everyone"
  on public.matches for select
  to anon, authenticated
  using (true);

grant select on public.matches to anon, authenticated;
revoke all on public.bookings from anon, authenticated;

