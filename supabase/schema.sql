create or replace function public.book_tickets(
  p_match_id bigint,
  p_customer_name text,
  p_customer_email text,
  p_customer_phone text,
  p_stand_category text,
  p_ticket_count integer,
  p_aisle_seats boolean default false,
  p_accessible_seating boolean default false
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_booking_id bigint;
begin
  if p_ticket_count not between 1 and 10 then
    raise exception using errcode = '22023', message = 'Ticket count must be between 1 and 10.';
  end if;

  if char_length(trim(p_customer_name)) not between 2 and 60 then
    raise exception using errcode = '22023', message = 'Name must be between 2 and 60 characters.';
  end if;

  if position('@' in p_customer_email) < 2 then
    raise exception using errcode = '22023', message = 'Enter a valid email address.';
  end if;

  if p_customer_phone !~ '^[0-9]{10}$' then
    raise exception using errcode = '22023', message = 'Phone number must contain exactly 10 digits.';
  end if;

  if p_stand_category not in ('general', 'premium', 'hospitality') then
    raise exception using errcode = '22023', message = 'Choose a valid stand category.';
  end if;

  update public.matches
  set available_seats = available_seats - p_ticket_count
  where id = p_match_id
    and available_seats >= p_ticket_count;

  if not found then
    raise exception using errcode = 'P0001', message = 'The match does not exist or has insufficient available seats.';
  end if;

  insert into public.bookings (
    match_id,
    customer_name,
    customer_email,
    customer_phone,
    stand_category,
    ticket_count,
    aisle_seats,
    accessible_seating
  )
  values (
    p_match_id,
    trim(p_customer_name),
    trim(p_customer_email),
    p_customer_phone,
    p_stand_category,
    p_ticket_count,
    coalesce(p_aisle_seats, false),
    coalesce(p_accessible_seating, false)
  )
  returning id into new_booking_id;

  return new_booking_id;
end;
$$;

revoke all on function public.book_tickets(bigint, text, text, text, text, integer, boolean, boolean) from public;
grant execute on function public.book_tickets(bigint, text, text, text, text, integer, boolean, boolean) to anon, authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'matches'
  ) then
    alter publication supabase_realtime add table public.matches;
  end if;
end;
$$;
